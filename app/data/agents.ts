export function findAgent(idOrSlug?: string) {
  return agents.find((a) => a.id === idOrSlug || a.slug === idOrSlug)
}

export function agentInitials(name: string) {
  return name
    .split(/\s+/)
    .filter((w) => /[A-Za-z]/.test(w[0] ?? ''))
    .slice(0, 2)
    .map((w) => w[0]!.toUpperCase())
    .join('')
}
